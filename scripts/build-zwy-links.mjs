#!/usr/bin/env node
// Generates static redirect pages for the ZWY Tech business-card QR codes.
// The printed QR code points at https://kainnne.com/<slug>/ forever; only zwy-links.json changes.
// Generated folders carry a .zwy-generated marker so stale ones are removed and real pages are never overwritten.
import { readFile, writeFile, mkdir, rm, readdir, access } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const { links } = JSON.parse(await readFile(resolve(root, "zwy-links.json"), "utf8"));
const pub = resolve(root, "public");
const MARK = ".zwy-generated";
const exists = (p) => access(p).then(() => true, () => false);
const esc = (v) => String(v).replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");

for (const d of await readdir(pub, { withFileTypes: true })) {
  if (d.isDirectory() && await exists(resolve(pub, d.name, MARK))) await rm(resolve(pub, d.name), { recursive: true, force: true });
}
await rm(resolve(pub, "z"), { recursive: true, force: true });   // legacy location
for (const [slug, { name, target }] of Object.entries(links)) {
  if (!/^[a-z0-9-]+$/.test(slug)) throw new Error(`bad slug: ${slug}`);
  const url = new URL(target).href;
  const html = `<!doctype html>
<html lang="zh-Hant"><head><meta charset="utf-8">
<title>哲威揚科技 ZWY Tech — ${esc(name)}</title>
<meta name="robots" content="noindex">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="refresh" content="0; url=${esc(url)}">
<link rel="canonical" href="${esc(url)}">
<script>location.replace(${JSON.stringify(url)});</script>
</head><body style="font-family:system-ui,sans-serif;padding:2rem">
<p>正在前往 <a href="${esc(url)}">${esc(url)}</a></p>
</body></html>
`;
  const dir = resolve(pub, slug);
  if (await exists(dir)) throw new Error(`public/${slug} already exists and is not a generated redirect`);
  await mkdir(dir, { recursive: true });
  await writeFile(resolve(dir, "index.html"), html);
  await writeFile(resolve(dir, MARK), "generated by scripts/build-zwy-links.mjs from zwy-links.json\n");
  console.log(`${slug}/ -> ${url}`);
}
